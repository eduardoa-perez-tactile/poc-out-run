#!/usr/bin/env python3
"""Pack the source's Ferrari color variants into the existing Ferrari1 UV layout.

No source pose, pivot, wheel effect or gameplay dimension changes. Each color is
an independently loaded texture; selecting a color does not load the catalog.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('player_car', Path(__file__).with_name('import-player-car.py'))
car = importlib.util.module_from_spec(spec)
spec.loader.exec_module(car)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    car.source_guard(args.source)
    reference = json.loads((ROOT / 'outrun/src/content/vehicles/ferrari1.manifest.ts').read_text().split(' = ', 1)[1].rsplit(' as const;', 1)[0])
    folder = args.source / 'Resources/Vehicles/PlayerCar'
    entries = []
    for index in range(1, 15):
        path = ROOT / f'outrun/assets/textures/player-ferrari{index}.png'
        entry = {'index': index - 1, 'group': f'player-ferrari{index}', 'texture': f'textures/player-ferrari{index}.png'}
        if index > 1:
            frames = copy.deepcopy(reference['body'] + reference['effects'])
            raw = [(folder / f'Ferraris/Ferrari{index}/c{n}.png').read_bytes() for n in range(1, 149)]
            raw += [(folder / f'Wheels/c{n}.png').read_bytes() for n in range(1, 29)]
            for frame, pixels in zip(frames, raw):
                car.require(list(car.png_info(pixels)) == frame['sourceSizePx'], f'Ferrari{index} changes source canvas')
            width, height, atlas = car.pack_atlas(frames, raw)
            car.require([width, height] == reference['atlas']['sizePx'], 'Color atlas changes dimensions')
            car.require(all(frame['atlasRectPx'] == original['atlasRectPx'] for frame, original in zip(frames, reference['body'] + reference['effects'])), 'Color atlas changes UVs')
            guid = str(uuid.uuid5(uuid.NAMESPACE_URL, f'outrun:{car.PIN}:player-ferrari{index}'))
            meta = f'guid = "{guid}"\nimporter = "texture"\n[settings]\nkind = "texture"\natlas = "none"\ntrim = false\ncompression = "none"\nmipmaps = false\n'
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(atlas)
                Path(str(path) + '.gmeta').write_text(meta)
            else:
                car.require(path.read_bytes() == atlas, f'Ferrari{index} atlas differs')
                car.require(Path(str(path) + '.gmeta').read_text() == meta, f'Ferrari{index} metadata differs')
            entry['sha256'] = hashlib.sha256(atlas).hexdigest()
        else:
            entry['sha256'] = reference['atlas']['sha256']
        entries.append(entry)
    target = ROOT / 'outrun/src/content/vehicles/player-colors.ts'
    content = '// Source Ferrari color variants; generated by scripts/art/import-player-colors.py.\n'
    content += '// All 148 body canvases, UVs, pivots and shared wheel frames match Ferrari1.\n'
    content += 'export const PLAYER_COLORS = ' + json.dumps(entries, indent=2) + ' as const;\n'
    if args.write:
        target.write_text(content)
    else:
        car.require(target.read_text() == content, 'Player color catalog differs')
    print(('Imported' if args.write else 'Verified') + ' 14 source color variants; shared geometry, independently loaded atlases')


if __name__ == '__main__':
    main()
