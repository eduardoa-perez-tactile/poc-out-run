#!/usr/bin/env python3
"""Pinned destination source art; deterministic two-page full-canvas packing.

--inventory builds/probes selected families without writing runtime files.
--source PATH --write requires explicit --maps; stage Map2/Map10 first.
--committed reconstructs selected manifests/pages from repository-only originals.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]
ASSETS=ROOT/'outrun/assets'
MANIFESTS=ROOT/'outrun/src/content/environments'
PIN='6882721c99bc79365f815f68d389bf5078129e68'
EXTRUDE=2
PAGE_WIDTH=1024
PAGE_HEIGHT=1280
OBJECT_COUNTS={2:36,3:39,4:48,5:53,6:51,7:38,8:35,9:33,10:51,11:27,12:41,13:40,14:41,15:49,16:45}
spec=importlib.util.spec_from_file_location('environment_png_codec',Path(__file__).with_name('import-player-car.py'))
png=importlib.util.module_from_spec(spec);spec.loader.exec_module(png)

def need(value,message):
    if not value:raise ValueError(message)
def sha(raw):return hashlib.sha256(raw).hexdigest()
def stem(map_id):
    need(type(map_id)is int and 2<=map_id<=16,'Unsupported destination map ID')
    return 'goal' if map_id==16 else f'map{map_id:02}'
def export_name(map_id):return 'GOAL_ART' if map_id==16 else f'MAP{map_id:02}_ART'
def data_for(map_id):
    d=json.loads((ASSETS/f'data/biomes/{stem(map_id)}.json').read_text())
    need(d['id']==map_id and d['sourceCommit']==PIN and d['$type']=='SourceBiome','Wrong canonical source biome')
    return d

def source_guard(source):
    def git(*args):return subprocess.check_output(['git','-C',str(source),*args],text=True).strip()
    need(git('rev-parse','HEAD')==PIN,'Source HEAD must match pinned revision')
    need(not git('status','--porcelain=v1','--untracked-files=no','--','Resources','src'),'Tracked source modifications')

def old_shared_inputs():
    text=(MANIFESTS/'map01.manifest.ts').read_text();payload=text.split('export const MAP01_ART = ',1)[1]
    old,end=json.JSONDecoder().raw_decode(payload);need(payload[end:].strip()=='as const;','Invalid preserved Map1 manifest')
    return {(o['sourcePath'],o['sha256']):o['image'] for o in old['images'] if o['sourcePath'].startswith('Resources/Maps/MapStartGoal/')}

def source_objects(data):
    mid=data['id'];stem(mid);objects=data['objects'];expected=OBJECT_COUNTS[mid]
    need(len(objects)==expected and objects,'Invalid local catalog')
    for i,o in enumerate(objects,1):
        folder='Resources/Maps/MapStartGoal' if mid==16 else f'Resources/Maps/MapLevels/Map{mid}'
        need(type(o['id'])is int and o['id']==i and o['sourcePath']==f'{folder}/{i}.png','Invalid local source object path/ID')
        need(len(o['sourceSizePx'])==2,'Invalid source canvas')
    return objects

def layout(images):
    """Height/width/local-ID shelves. Page height is cropped to last extrusion."""
    need(images and len({x['objectId'] for x in images})==len(images) and all(type(x['objectId'])is int and x['objectId']>0 for x in images),'Empty/duplicate source IDs')
    order=sorted(images,key=lambda x:(-x['sourceSizePx'][1],-x['sourceSizePx'][0],x['objectId']))
    pages=[];rects={};page=0;x=y=row_height=0
    for image in order:
        w,h=image['sourceSizePx'];need(all(type(v)is int and v>0 for v in (w,h)),'Invalid source dimensions')
        outer_w=w+4;outer_h=h+4
        need(outer_w<=PAGE_WIDTH and outer_h<=PAGE_HEIGHT,'Source canvas exceeds page bound')
        if x+outer_w>PAGE_WIDTH:x=0;y+=row_height;row_height=0
        if y+outer_h>PAGE_HEIGHT:
            pages.append([PAGE_WIDTH,y+row_height]);page+=1;x=y=row_height=0
        need(page<2,'Destination exceeds two-page bound')
        rects[image['objectId']]=(page,[x+2,y+2,w,h]);x+=outer_w;row_height=max(row_height,outer_h)
    pages.append([PAGE_WIDTH,y+row_height])
    return pages,rects

def source_probe(w,h,pixels):
    need(len(pixels)==w*h*4,'Source pixel length mismatch')
    max_alpha=max(pixels[3::4]);kind='opaque' if max_alpha==255 else 'alpha' if max_alpha>0 else 'transparent'
    if max_alpha:
        _,py,px=min((abs(px-w/2)+abs(py-h/2),py,px) for py in range(h) for px in range(w) if pixels[(py*w+px)*4+3]==max_alpha)
    else:px,py=w//2,h//2
    at=(py*w+px)*4
    return {'kind':kind,'pixelPx':[px,py],'rgba':list(pixels[at:at+4])}

def decode_source(raw):return png.decode_png(raw,max_dimension=4096,require_alpha=False)
def manifest_text(manifest):
    return '// Generated by scripts/art/import-environments.py; image metadata only, never collision data.\nimport type {EnvironmentArtManifest} from \'./environment-art.ts\';\nexport const '+export_name(manifest['mapId'])+' = '+json.dumps(manifest,indent=2)+' as const satisfies EnvironmentArtManifest;\n'
def load_manifest(map_id):
    text=(MANIFESTS/f'{stem(map_id)}.manifest.ts').read_text();payload=text.split('export const '+export_name(map_id)+' = ',1)[1]
    data,end=json.JSONDecoder().raw_decode(payload)
    need(payload[end:].strip()=='as const satisfies EnvironmentArtManifest;','Invalid destination manifest suffix')
    return data

def build(data,read):
    mid=data['id'];name=stem(mid);shared=old_shared_inputs();images=[];originals={};decoded={};audit=[]
    for o in source_objects(data):
        raw=read(o['sourcePath']);need(sha(raw)==o['sha256'],'Source PNG hash mismatch: '+o['sourcePath'])
        w,h,pixels=decode_source(raw);need([w,h]==o['sourceSizePx'],'Canonical source dimensions differ')
        key=shared.get((o['sourcePath'],o['sha256'])) if mid==16 else None
        if key is None:key=f'art/environments/{name}/objects/object-{o["id"]:03}.png'
        probe=source_probe(w,h,pixels)
        images.append({'objectId':o['id'],'sourcePath':o['sourcePath'],'image':key,'sourceSizePx':[w,h],'sha256':sha(raw),'page':0,'atlasRectPx':[],'sourceProbe':probe})
        originals[key]=raw;decoded[o['id']]=(w,h,pixels)
        audit.append({'objectId':o['id'],'sourcePath':o['sourcePath'],'probe':probe,'maxAlpha':max(pixels[3::4]),'opaquePixels':pixels[3::4].count(255),'bitDepth':raw[24],'pngColorType':raw[25]})
    sizes,rects=layout(images);page_pixels=[bytearray(w*h*4) for w,h in sizes]
    for image in images:
        i=image['objectId'];page,rect=rects[i];image['page']=page;image['atlasRectPx']=rect
        x,y,w,h=rect;pixels=decoded[i][2];target=page_pixels[page];aw=sizes[page][0]
        for dy in range(-2,h+2):
            sy=min(h-1,max(0,dy));row=pixels[sy*w*4:(sy+1)*w*4];expanded=row[:4]*2+row+row[-4:]*2
            at=((y+dy)*aw+x-2)*4;target[at:at+len(expanded)]=expanded
    pages=[];runtime={}
    for page,((w,h),pixels) in enumerate(zip(sizes,page_pixels)):
        raw=png.encode_png(w,h,pixels);key=f'textures/environments/{name}-props-{page}.png';runtime[key]=raw
        pages.append({'image':key,'sizePx':[w,h],'extrudePx':2,'sha256':sha(raw)})
    backgrounds={};folder='Resources/Maps/MapStartGoal' if mid==16 else f'Resources/Maps/MapLevels/Map{mid}'
    for layer,width in [('back',2182 if mid==16 else 1536),('front',2048)]:
        path=f'{folder}/{layer}.png';raw=read(path);w,h,pixels=decode_source(raw)
        need([w,h]==[width,256],'Panorama dimensions differ: '+path)
        key=f'textures/environments/{name}-{layer}.png';runtime[key]=raw
        backgrounds[layer]={'sourcePath':path,'image':key,'sizePx':[w,h],'sha256':sha(raw),'sourceProbe':source_probe(w,h,pixels)}
    manifest={'assetId':name+'-environment','mapId':mid,'sourceCommit':PIN,'pages':pages,'images':images,**backgrounds}
    return {'manifest':manifest,'originals':originals,'runtime':runtime,'audit':audit}

def committed_build(map_id):
    data=data_for(map_id);manifest=load_manifest(map_id);shared=old_shared_inputs();allowed={}
    for o in source_objects(data):
        key=shared.get((o['sourcePath'],o['sha256'])) if map_id==16 else None
        allowed[o['sourcePath']]=key or f'art/environments/{stem(map_id)}/objects/object-{o["id"]:03}.png'
    folder='Resources/Maps/MapStartGoal' if map_id==16 else f'Resources/Maps/MapLevels/Map{map_id}'
    for layer in ('back','front'):allowed[f'{folder}/{layer}.png']=f'textures/environments/{stem(map_id)}-{layer}.png'
    # Authored manifest is never used as an arbitrary filesystem read path.
    for image in manifest['images']:need(allowed.get(image['sourcePath'])==image['image'],'Noncanonical committed image path')
    for layer in ('back','front'):need(allowed.get(manifest[layer]['sourcePath'])==manifest[layer]['image'],'Noncanonical committed panorama path')
    return build(data,lambda path:(ASSETS/allowed[path]).read_bytes())

def verify(result):
    m=result['manifest'];need(load_manifest(m['mapId'])==m,'Destination manifest differs')
    need((MANIFESTS/f'{stem(m["mapId"])}.manifest.ts').read_text()==manifest_text(m),'Manifest text differs')
    for key,raw in {**result['originals'],**result['runtime']}.items():need((ASSETS/key).read_bytes()==raw,'Imported PNG differs: '+key)
    expected={ASSETS/x['image'] for x in m['images'] if x['image'].startswith(f'art/environments/{stem(m["mapId"])}/')}
    folder=ASSETS/f'art/environments/{stem(m["mapId"])}/objects'
    need(set(folder.glob('*.png'))==expected,'Unexpected/missing original destination PNGs')

def write_result(result):
    # Existing reused goal originals are verified byte-exact, never rewritten.
    for key,raw in {**result['originals'],**result['runtime']}.items():
        path=ASSETS/key
        if key.startswith('art/environments/map01/'):
            need(path.read_bytes()==raw,'Preserved Map1 shared source differs');continue
        path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    m=result['manifest'];MANIFESTS.mkdir(parents=True,exist_ok=True);(MANIFESTS/f'{stem(m["mapId"])}.manifest.ts').write_text(manifest_text(m))

def parse_maps(text):
    try:values=[int(v) for v in text.split(',')]
    except ValueError as error:raise argparse.ArgumentTypeError('Expected comma-separated map IDs2..16') from error
    if not values or len(set(values))!=len(values) or any(v<2 or v>16 for v in values):raise argparse.ArgumentTypeError('Map IDs must be unique2..16')
    return sorted(values)

def main():
    parser=argparse.ArgumentParser(description=__doc__);group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--source',type=Path);group.add_argument('--committed',action='store_true')
    parser.add_argument('--maps',type=parse_maps);parser.add_argument('--inventory',action='store_true');parser.add_argument('--write',action='store_true')
    parser.add_argument('--report',type=Path);args=parser.parse_args()
    need(not args.write or (args.source and args.maps and not args.inventory),'--write requires pinned --source and explicit --maps without --inventory')
    if args.source:source_guard(args.source)
    maps=args.maps or list(range(2,17));report={'sourceCommit':PIN,'scope':'Offline source inventory/pixel/packing; not GPU readiness','maps':[]}
    for mid in maps:
        result=build(data_for(mid),lambda path:(args.source/path).read_bytes()) if args.source else committed_build(mid)
        if args.write:write_result(result)
        if not args.inventory:verify(result)
        m=result['manifest'];report['maps'].append({'mapId':mid,'objects':len(m['images']),'pages':m['pages'],'back':m['back'],'front':m['front'],
            'alphaExceptions':[x for x in result['audit'] if x['probe']['kind']!='opaque'],'opaqueObjects':sum(x['probe']['kind']=='opaque' for x in result['audit']),
            'reusedOldInputs':sum(x['image'].startswith('art/environments/map01/') for x in m['images']),
            'objectPngEncodingCounts':{str(t):sum(x['pngColorType']==t for x in result['audit']) for t in sorted({x['pngColorType'] for x in result['audit']})}})
    if args.report:args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'maps':maps,'objects':sum(m['objects'] for m in report['maps']),'panoramas':2*len(maps),'alphaExceptions':sum(len(m['alphaExceptions']) for m in report['maps']),'scope':report['scope']}))

if __name__=='__main__':
    try:main()
    except (ValueError,OSError,KeyError,subprocess.CalledProcessError) as error:raise SystemExit(str(error))
