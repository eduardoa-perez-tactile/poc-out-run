#!/usr/bin/env python3
"""Import/check the complete pinned traffic catalog using Python stdlib only."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[2]
PIN='6882721c99bc79365f815f68d389bf5078129e68'
MANIFEST=ROOT/'outrun/src/content/vehicles/traffic-source.manifest.ts'
REFERENCE=ROOT/'outrun/assets/textures/traffic-catalog-reference.png'
WIDTH,HEIGHT,EXTRUDE=1024,2048,2
spec=importlib.util.spec_from_file_location('traffic_png',Path(__file__).with_name('import-player-car.py'))
png=importlib.util.module_from_spec(spec);spec.loader.exec_module(png)

def require(value,message):
    if not value:raise ValueError(message)
def sha(raw):return hashlib.sha256(raw).hexdigest()
def source_guard(source):
    def git(*args):return subprocess.check_output(['git','-C',str(source),*args],text=True).strip()
    require(git('rev-parse','HEAD')==PIN,'Source HEAD must match pinned revision')
    require(not git('status','--porcelain=v1','--untracked-files=no','--','Resources','src'),'Source Resources/src has tracked modifications')
def source_path(model,frame):return f'Vehicles/TrafficCars/Car{model}/c{frame}.png'
def raw_path(model,frame):return f'art/vehicles/traffic/car{model:02}/c{frame:03}.png'
def properties_path(model):return f'Vehicles/TrafficCars/Car{model}/Car{model}.txt'
def raw_properties_path(model):return f'art/vehicles/traffic/car{model:02}/Car{model}.txt'
def scale_property(raw,model):
    match=re.fullmatch(rb'\s*SCALE:\s*(0\.9|1\.3)\s*',raw)
    require(match is not None,'Invalid traffic SCALE property')
    scale=float(match[1]);require(scale==(.9 if model in (1,7,13,19,25) else 1.3),'Unexpected source SCALE for model '+str(model))
    return scale

def layout(frames):
    require(len(frames)>0,'Empty traffic frame list')
    keys=[(f['modelId'],f['sourceFrame']) for f in frames]
    require(len(set(keys))==len(keys),'Duplicate traffic frame identity')
    x=y=row_height=0;rects={}
    for frame in sorted(frames,key=lambda f:(-f['sourceSizePx'][1],-f['sourceSizePx'][0],f['modelId'],f['sourceFrame'])):
        w,h=frame['sourceSizePx']
        require(type(w) is int and type(h) is int and w>0 and h>0,'Invalid traffic canvas')
        require(w+4<=WIDTH and h+4<=HEIGHT,'Traffic canvas exceeds atlas')
        if x+w+4>WIDTH:x=0;y+=row_height;row_height=0
        require(y+h+4<=HEIGHT,'Traffic atlas overflow')
        rects[(frame['modelId'],frame['sourceFrame'])]=[x+2,y+2,w,h]
        x+=w+4;row_height=max(row_height,h+4)
    return rects

def build(read):
    models=[];frames=[];originals={};decoded={};properties={}
    for model in range(1,33):
        raw=read(properties_path(model));properties[model]=raw
        entry={'id':model,'scale':scale_property(raw,model),'propertiesSha256':sha(raw),
               'propertiesImage':raw_properties_path(model),'propertiesSourcePath':properties_path(model),'frames':[]}
        for frame in range(1,17):
            path=source_path(model,frame);raw=read(path);w,h,pixels=png.decode_png(raw)
            require(any(pixels[i]==0 for i in range(3,len(pixels),4)),'Traffic source needs transparent background')
            probes=[(abs(x-w/2)+abs(y-h/2),y,x) for y in range(h) for x in range(w) if pixels[(y*w+x)*4+3]==255]
            require(probes,'Traffic source has no opaque probe')
            _,py,px=min(probes)
            item={'sourceFrame':frame,'image':raw_path(model,frame),'sourcePath':path,'sourceSizePx':[w,h],
                  'groundAnchorPx':[w/2,h],'sha256':sha(raw),'atlasRectPx':[],
                  'opaqueProbePx':[px,py],'opaqueProbeRgba':list(pixels[(py*w+px)*4:(py*w+px)*4+4])}
            entry['frames'].append(item);frames.append({'modelId':model,**item});originals[(model,frame)]=raw;decoded[(model,frame)]=(w,h,pixels)
        models.append(entry)
    rects=layout(frames);atlas=bytearray(WIDTH*HEIGHT*4)
    for model in models:
        for frame in model['frames']:
            key=(model['id'],frame['sourceFrame']);w,h,pixels=decoded[key];x,y,_,_=rects[key];frame['atlasRectPx']=rects[key]
            for dy in range(-2,h+2):
                sy=max(0,min(h-1,dy));row=pixels[sy*w*4:(sy+1)*w*4];expanded=row[:4]*2+row+row[-4:]*2
                at=((y+dy)*WIDTH+x-2)*4;atlas[at:at+len(expanded)]=expanded
    packed=png.encode_png(WIDTH,HEIGHT,atlas)
    catalog={'assetId':'traffic-source','sourceCommit':PIN,'atlas':{'image':'textures/traffic-source.png','sizePx':[WIDTH,HEIGHT],'extrudePx':2,'sha256':sha(packed)},'models':models}
    return catalog,originals,properties,packed

TYPES='''// Generated by scripts/art/import-traffic.py; source pixels/visual scale only, never colliders.
export interface TrafficFrame {
  readonly sourceFrame:number;readonly image:string;readonly sourcePath:string;
  readonly sourceSizePx:readonly[number,number];readonly groundAnchorPx:readonly[number,number];readonly sha256:string;
  readonly atlasRectPx:readonly[number,number,number,number];readonly opaqueProbePx:readonly[number,number];
  readonly opaqueProbeRgba:readonly[number,number,number,number];
}
export interface TrafficModel {
  readonly id:number;readonly scale:.9|1.3;readonly propertiesSha256:string;
  readonly propertiesImage:string;readonly propertiesSourcePath:string;readonly frames:readonly TrafficFrame[];
}
export interface TrafficCatalog {
  readonly assetId:'traffic-source';readonly sourceCommit:string;
  readonly atlas:{readonly image:string;readonly sizePx:readonly[number,number];readonly extrudePx:number;readonly sha256:string};
  readonly models:readonly TrafficModel[];
}
export const TRAFFIC_SOURCE:TrafficCatalog = '''
def manifest_text(catalog):return TYPES+json.dumps(catalog,indent=2)+';\n'
def load_manifest(path=MANIFEST):
    payload=path.read_text().split('export const TRAFFIC_SOURCE:TrafficCatalog = ',1)[1]
    data,end=json.JSONDecoder().raw_decode(payload);require(payload[end:].strip()==';','Invalid traffic manifest suffix');return data

def committed_build():
    # Reconstruct paths solely from fixed IDs, never from unchecked manifest text.
    paths={source_path(m,f):raw_path(m,f) for m in range(1,33) for f in range(1,17)}
    paths.update({properties_path(m):raw_properties_path(m) for m in range(1,33)})
    return build(lambda path:(ROOT/'outrun'/paths[path]).read_bytes())

def reference_png(catalog,originals):
    """Independent original-pixel controls, not copied atlas or GPU readbacks.

    Column=model-1, row=sourceFrame-1. The catalog identifies the verified source
    coordinate; decode its original file again rather than trusting recorded RGBA.
    This tiny test-only asset traverses the same renderer transfer as the atlas.
    """
    pixels=bytearray(32*16*4)
    for model in catalog['models']:
        for frame in model['frames']:
            w,h,source=png.decode_png(originals[(model['id'],frame['sourceFrame'])])
            x,y=frame['opaqueProbePx']
            require(type(x) is int and type(y) is int and 0<=x<w and 0<=y<h,'Invalid traffic reference source coordinate')
            rgba=source[(y*w+x)*4:(y*w+x+1)*4]
            require(rgba[3]==255,'Traffic reference requires opaque original source pixel')
            at=((frame['sourceFrame']-1)*32+model['id']-1)*4
            pixels[at:at+4]=rgba
    return png.encode_png(32,16,pixels)

def verify(catalog,originals,properties,packed):
    require(MANIFEST.read_text()==manifest_text(catalog),'Traffic catalog differs')
    require((ROOT/'outrun/assets'/catalog['atlas']['image']).read_bytes()==packed,'Traffic atlas differs')
    require(REFERENCE.read_bytes()==reference_png(catalog,originals),'Traffic source-color reference differs')
    expected=set()
    for model in catalog['models']:
        m=model['id'];path=ROOT/'outrun'/raw_properties_path(m);expected.add(path)
        require(path.read_bytes()==properties[m],'Traffic SCALE source differs')
        for frame in model['frames']:
            path=ROOT/'outrun'/raw_path(m,frame['sourceFrame']);expected.add(path)
            require(path.read_bytes()==originals[(m,frame['sourceFrame'])],'Traffic source PNG differs')
    actual={p for p in (ROOT/'outrun/art/vehicles/traffic').rglob('*') if p.is_file()}
    require(actual==expected,'Unexpected or missing traffic source files')

def atomic_write(path,raw):
    path.parent.mkdir(parents=True,exist_ok=True)
    temporary=None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent,prefix='.'+path.name+'.',delete=False) as handle:
            temporary=Path(handle.name);handle.write(raw)
        os.replace(temporary,path)
    finally:
        if temporary is not None:temporary.unlink(missing_ok=True)

def publish(catalog,originals,properties,packed):
    for model in catalog['models']:
        m=model['id'];atomic_write(ROOT/'outrun'/raw_properties_path(m),properties[m])
        for frame in model['frames']:atomic_write(ROOT/'outrun'/raw_path(m,frame['sourceFrame']),originals[(m,frame['sourceFrame'])])
    atomic_write(ROOT/'outrun/assets'/catalog['atlas']['image'],packed)
    atomic_write(REFERENCE,reference_png(catalog,originals))
    # Catalog last: consumers never see a partially-written TypeScript module.
    atomic_write(MANIFEST,manifest_text(catalog).encode())

def main():
    parser=argparse.ArgumentParser(description=__doc__);group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--source',type=Path);group.add_argument('--committed',action='store_true');parser.add_argument('--write',action='store_true');args=parser.parse_args()
    require(not args.write or args.source is not None,'--write requires pinned --source')
    if args.source:
        source_guard(args.source);values=build(lambda path:(args.source/'Resources'/path).read_bytes())
    else:values=committed_build()
    if args.write:publish(*values)
    verify(*values)
    print('Verified32 traffic models ×16 original frames,32 SCALE files,1024×2048 atlas,32×16 independent source-color control; source pixels unchanged')
if __name__=='__main__':
    try:main()
    except (ValueError,OSError,KeyError,subprocess.CalledProcessError) as error:raise SystemExit(str(error))
